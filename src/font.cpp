namespace {

    std::string get_font(const int terminal_id)
    {
        switch (terminal_id) {
            case 1:  // VT220 - 8x10
            case 2:  // VT240 - 8x10
                return font_8x10;
            case 24:  // VT320 - 15x12
            case 42:  // VT1000 - unknown, assumed VT320 compatible
                return font_15x12;
            case 18:  // VT330 - 10x20
            case 19:  // VT340 - 10x20
                return font_10x20;
            case 32:  // VT382J - 12x30
            case 44:  // VT382T - 12x30
                return font_12x30;
            case 41:  // VT420 - 10x16
            case 61:  // VT510 - 10x16
            case 64:  // VT520 - 10x16
            case 65:  // VT525 - 10x16
            case 66:  // VTStar - 10x16
                return font_10x16;
            default:  // Unknown - assume 10x16
                return font_10x16;
        }
    }

}  // namespace

soft_font::soft_font(capabilities& caps)
{
    auto font_data = get_font(caps.terminal_id);
    if (caps.has_soft_fonts && !font_data.empty()) {
        // The VT200 family don't support full cell fonts, so we need to use
        // a different rendering technique with a slightly different glyph set.
        // We record the full-cell capability here so the board renderer knows
        // which format it should be using.
        caps.has_full_cell_fonts = font_data != font_8x10;
        // Some terminals (like RLogin) will not cope with DECDLD content
        // containing newlines, so we need to strip those out first.
        for (auto i = 0; i < font_data.size(); i++)
            if (font_data[i] == '\n')
                font_data.erase(i--, 1);
        std::cout << "\033P" << font_data << "\033\\";
        // VTStar seems to get itself stuck when downloading a soft font, but
        // that can be fixed by flooding it with a bunch of SGR sequences.
        if (caps.terminal_id == 66)
            for (auto i = 0; i < 100; i++)
                std::cout << "\033[0;1m";
        std::cout << "\033[m";
        // Designate our soft font in G1.
        std::cout << "\033) @";
    }
}

soft_font::~soft_font()
{
    // Restore default character sets with DECSTR.
    std::cout << "\033[!p";
}
